# -*- coding: utf-8 -*-
"""
common_core.strategy.portfolio 的单元测试

这个文件是干嘛的？
    组合级执行器最容易踩坑的地方只有一个：爆仓口径。
    因为组合保证金（Portfolio Margin）/ 统一账户的本质是：
        多个仓位共享同一份账户权益（同一个“钱包”）

所以这里用极小的例子确保两件事：
    1) 爆仓检查按“总敞口（各持仓名义之和）”来算
    2) mark-to-market（结算浮动盈亏）会叠加到组合权益里
"""

from __future__ import annotations

import unittest

from common_core.strategy import 盘口快照, 仓位方向, 目标仓位, 策略输出
from common_core.strategy import 组合盘口调仓执行器


class Test组合盘口调仓执行器(unittest.TestCase):
    def test_爆仓按总敞口(self) -> None:
        执行器 = 组合盘口调仓执行器(
            初始资金=1000.0,
            数量步进=1.0,
            手续费率=0.0,
            滑点率=0.0,
            最小下单名义=0.0,
            # 让它更容易触发：总敞口 2000 时，保证金率=0.5 < 0.51 => 爆
            最小维持保证金率=0.51,
            结算价模式="mid",
        )

        # 两个币的初始盘口（为了让测试只关注“爆仓口径”，这里把 bid=ask=100）
        执行器.推进盘口快照结算(
            盘口快照(
                交易对="AAA",
                时间_ms=0,
                bid价=(100.0,),
                bid量=(1.0,),
                ask价=(100.0,),
                ask量=(1.0,),
            )
        )
        执行器.推进盘口快照结算(
            盘口快照(
                交易对="BBB",
                时间_ms=0,
                bid价=(100.0,),
                bid量=(1.0,),
                ask价=(100.0,),
                ask量=(1.0,),
            )
        )

        # 先开 AAA：1x 名义杠杆 -> 名义=1000 -> qty=10
        执行器.执行策略输出(
            策略输出(目标仓位=目标仓位(交易对="AAA", 方向=仓位方向.多, 名义杠杆=1.0))
        )
        self.assertFalse(执行器.是否爆仓)

        # 再开 BBB：组合总敞口翻倍 -> 触发爆仓
        执行器.执行策略输出(
            策略输出(目标仓位=目标仓位(交易对="BBB", 方向=仓位方向.多, 名义杠杆=1.0))
        )
        self.assertTrue(执行器.是否爆仓)
        self.assertAlmostEqual(执行器.获取组合账户状态().账户权益, 0.0, places=12)

    def test_结算会叠加盈亏(self) -> None:
        执行器 = 组合盘口调仓执行器(
            初始资金=1000.0,
            数量步进=1.0,
            手续费率=0.0,
            滑点率=0.0,
            最小下单名义=0.0,
            最小维持保证金率=0.005,
            结算价模式="mid",
        )

        # 初始：AAA mid=100（同样用 bid=ask 简化，避免成本扰动）
        执行器.推进盘口快照结算(
            盘口快照(
                交易对="AAA",
                时间_ms=0,
                bid价=(100.0,),
                bid量=(1.0,),
                ask价=(100.0,),
                ask量=(1.0,),
            )
        )

        执行器.执行策略输出(
            策略输出(目标仓位=目标仓位(交易对="AAA", 方向=仓位方向.多, 名义杠杆=1.0))
        )
        初始权益 = 执行器.获取组合账户状态().账户权益
        self.assertAlmostEqual(初始权益, 1000.0, places=12)

        # 价格上涨：AAA mid 从 100 -> 110，权益应增加 qty*(110-100)
        执行器.推进盘口快照结算(
            盘口快照(
                交易对="AAA",
                时间_ms=1000,
                bid价=(110.0,),
                bid量=(1.0,),
                ask价=(110.0,),
                ask量=(1.0,),
            )
        )

        状态 = 执行器.获取单品种账户状态("AAA")
        self.assertGreater(状态.账户权益, 1000.0)
