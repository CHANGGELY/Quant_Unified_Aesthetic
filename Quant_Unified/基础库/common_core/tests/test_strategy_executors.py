# -*- coding: utf-8 -*-
"""
common_core.strategy.executors 的单元测试

这个文件是干嘛的？
    我们最近新增了“对冲撮合执行器”（支持同时持有多头/空头）。
    这类改动属于“地基代码”，一旦写错，所有策略回测都会跟着偏。

所以这里写几个很小但很关键的测试，确保：
    1) 对冲执行器强制要求挂单带仓位方向（LONG/SHORT）
    2) OHLC 轨迹撮合能正常让多空同时开仓
    3) 平仓单数量超过持仓时，回测会自动裁切为“最多平到 0”
       （避免成交量虚报、手续费多扣）
"""

from __future__ import annotations

import unittest

from common_core.strategy import (
    K线,
    K线对冲撮合执行器,
    K线撮合执行器,
    仓位方向,
    成交回报,
    策略输出,
    订单方向,
    限价挂单,
)


class TestK线对冲撮合执行器(unittest.TestCase):
    def test_必须提供仓位方向(self):
        执行器 = K线对冲撮合执行器(交易对="TEST", 初始资金=1000.0)
        输出 = 策略输出(
            目标挂单=[
                限价挂单(
                    交易对="TEST",
                    方向=订单方向.买,
                    价格=100.0,
                    数量=1.0,
                    仓位方向=None,  # 故意不填
                )
            ]
        )
        with self.assertRaises(ValueError):
            执行器.执行策略输出(输出)

    def test_多空可同时开仓_权益计算正确(self):
        执行器 = K线对冲撮合执行器(交易对="TEST", 初始资金=1000.0)
        执行器.设置最新价(100.0)

        输出 = 策略输出(
            目标挂单=[
                # 下跌段撞到 90 -> 开多
                限价挂单(
                    交易对="TEST",
                    方向=订单方向.买,
                    价格=90.0,
                    数量=1.0,
                    仓位方向=仓位方向.多,
                ),
                # 上涨段撞到 110 -> 开空
                限价挂单(
                    交易对="TEST",
                    方向=订单方向.卖,
                    价格=110.0,
                    数量=1.0,
                    仓位方向=仓位方向.空,
                ),
            ]
        )
        执行器.执行策略输出(输出)

        k线 = K线(
            开始时间_ms=0,
            收盘时间_ms=60_000,
            开=100.0,
            高=120.0,
            低=80.0,
            收=100.0,
        )
        成交: list[成交回报] = 执行器.推进K线(k线)
        self.assertEqual(len(成交), 2)

        状态 = 执行器.获取账户状态()
        self.assertAlmostEqual(状态.多头持仓数量, 1.0, places=12)
        self.assertAlmostEqual(状态.空头持仓数量, 1.0, places=12)
        # 收盘价=100：多头浮盈=+10，空头浮盈=+10，总权益=1020
        self.assertAlmostEqual(状态.账户权益, 1020.0, places=6)

    def test_平仓数量超过持仓会裁切(self):
        执行器 = K线对冲撮合执行器(交易对="TEST", 初始资金=1000.0)

        # 先开多 1
        执行器.执行策略输出(
            策略输出(
                目标挂单=[
                    限价挂单(
                        交易对="TEST",
                        方向=订单方向.买,
                        价格=100.0,
                        数量=1.0,
                        仓位方向=仓位方向.多,
                    )
                ]
            )
        )
        _ = 执行器.推进K线(
            K线(开始时间_ms=0, 收盘时间_ms=60_000, 开=100.0, 高=100.0, 低=99.0, 收=100.0)
        )

        # 再用“超量平仓单”尝试平多 2（真实交易所最多平到 0）
        执行器.执行策略输出(
            策略输出(
                目标挂单=[
                    限价挂单(
                        交易对="TEST",
                        方向=订单方向.卖,
                        价格=100.0,
                        数量=2.0,
                        只减仓=True,
                        仓位方向=仓位方向.多,
                    )
                ]
            )
        )
        成交 = 执行器.推进K线(
            K线(开始时间_ms=60_000, 收盘时间_ms=120_000, 开=100.0, 高=101.0, 低=99.0, 收=100.0)
        )
        self.assertEqual(len(成交), 1)
        self.assertAlmostEqual(成交[0].成交量, 1.0, places=12)

        状态 = 执行器.获取账户状态()
        self.assertAlmostEqual(状态.多头持仓数量, 0.0, places=12)


class TestK线撮合执行器(unittest.TestCase):
    def test_reduce_only_超量平仓会裁切(self):
        执行器 = K线撮合执行器(
            交易对="TEST",
            初始资金=1000.0,
            初始持仓数量=1.0,
            初始持仓均价=100.0,
            maker_fee=0.0,
            启用迟滞更新=False,
        )

        执行器.执行策略输出(
            策略输出(
                目标挂单=[
                    限价挂单(
                        交易对="TEST",
                        方向=订单方向.卖,
                        价格=110.0,
                        数量=2.0,  # 故意超量
                        只减仓=True,
                    )
                ]
            )
        )

        成交 = 执行器.推进K线(
            K线(开始时间_ms=0, 收盘时间_ms=60_000, 开=110.0, 高=110.0, 低=110.0, 收=110.0)
        )
        self.assertEqual(len(成交), 1)
        self.assertAlmostEqual(成交[0].成交量, 1.0, places=12)

        状态 = 执行器.获取账户状态()
        self.assertAlmostEqual(状态.持仓数量, 0.0, places=12)


if __name__ == "__main__":
    unittest.main()

