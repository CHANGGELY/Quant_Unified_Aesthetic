"""
common_core.strategy - 策略接口与执行器“公共地基”

这个包是干嘛的？
    你可以把量化系统想成“有脑子、有手脚”的机器人：
    - 策略（脑子）：只负责思考——根据行情和账户状态，输出“我想怎么做”
    - 执行器（手脚）：只负责执行——回测里做撮合，实盘里下真实订单

为什么要分开？
    如果脑子和手脚搅在一起：
    - 回测一套逻辑、实盘一套逻辑，最后你根本不知道自己到底在跑哪套策略

这个包提供什么？
    - 通用数据结构（K线、订单、成交、账户状态）
    - 策略/执行器的接口（像“插座标准”一样），方便不同策略复用同一套回测/实盘执行环境

注意：
    这里是“地基”，不直接绑定某个交易所，也不直接绑定某个策略。
"""

