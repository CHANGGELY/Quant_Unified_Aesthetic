# -*- coding: utf-8 -*-
"""
common_core.strategy.interfaces - “插座标准”：策略和执行器怎么对接

这个文件是干嘛的？
    如果每个策略都用不同的函数签名（参数/返回值），那回测/实盘执行环境就没法复用。
    所以这里定义“接口（Interface）”：
    - 策略接口：策略必须提供哪些能力
    - 执行器接口：执行环境必须提供哪些能力

接口你可以理解成“插座标准”：
    - 只要插头（策略）遵守标准
    - 不同国家（回测/实盘/不同交易所）的插座（执行器）都能插

术语解释：
    - Protocol（协议接口）：Python 的一种“软接口”，不强制继承，但会做类型检查（更灵活）。
"""

from __future__ import annotations

from typing import Protocol

from .models import K线, 盘口快照, 账户状态, 成交回报, 策略输出


class 策略接口(Protocol):
    """
    策略接口：策略的“最小可用能力”
    """

    @property
    def 策略名称(self) -> str:  # pragma: no cover
        ...

    def 在K线收盘(self, k线: K线, 账户: 账户状态) -> 策略输出:  # pragma: no cover
        """
        输入：
            - 一根已收盘的 K 线（1m 或更大周期）
            - 当前账户状态（余额、持仓等）

        输出：
            - 本次决策想做的动作（不直接下单）：
              - 目标挂单：给“挂单撮合/做市”类执行器用
              - 目标仓位：给“调仓/信号”类执行器用
        """
        ...

    def 在价格更新(self, 时间_ms: int, 最新价: float, 账户: 账户状态) -> 策略输出 | None:  # pragma: no cover
        """
        可选接口：价格更新驱动（tick/秒级）

        什么时候需要它？
            像网格/做市这类策略，往往需要“价格每动一下就更新边界”，
            只靠 1 分钟收盘会显得反应太慢。

        返回值：
            - 返回 策略输出：表示你想更新挂单/仓位
            - 返回 None：表示本次价格更新不需要动作
        """
        ...

    def 在成交回报(self, 回报: 成交回报) -> None:  # pragma: no cover
        """
        当交易所推送成交回报时，策略可以用它来更新内部状态（可选实现）。
        """
        ...


class 执行器接口(Protocol):
    """
    执行器接口：执行环境的“最小可用能力”

    回测执行器/实盘执行器都会实现它。
    """

    def 获取账户状态(self) -> 账户状态:  # pragma: no cover
        ...

    def 执行策略输出(self, 输出: 策略输出) -> None:  # pragma: no cover
        """
        把策略输出变成真实动作：
        - 回测：撮合成交、更新账户
        - 实盘：下单/撤单、等待 WebSocket 成交推送
        """
        ...


class 盘口策略接口(策略接口, Protocol):
    """
    盘口策略接口：给“高频盘口策略”准备的扩展接口

    术语解释：
        - L2（Level 2）：指更“深”的盘口信息（不止买一卖一，而是很多档位的价格与数量）
          你可以理解成：不仅看“队伍最前面是谁”，还看“队伍后面排了多少人”。

    设计目标：
        - 让策略脑子能用盘口快照驱动（100ms/1s 级别），而不是只能等 1 分钟 K 线收盘。
        - 同时保持对老策略完全兼容：老策略只实现 `在K线收盘` 也能跑。
    """

    def 在盘口快照(self, 快照: 盘口快照, 账户: 账户状态) -> 策略输出 | None:  # pragma: no cover
        """
        输入：一帧盘口快照 + 当前账户状态
        输出：本次是否需要更新仓位/挂单；不需要就返回 None。
        """
        ...


class 盘口执行器接口(执行器接口, Protocol):
    """
    盘口执行器接口：给“盘口驱动回测/实盘执行器”准备的扩展接口
    """

    def 推进盘口快照结算(self, 快照: 盘口快照) -> None:  # pragma: no cover
        """
        用盘口快照更新“最新价/权益/风险检查”等状态。

        类比：
            - K线调仓执行器：推进K线结算（每分钟结算一次）
            - 盘口调仓执行器：推进盘口快照结算（每 100ms/1s 结算一次）
        """
        ...
